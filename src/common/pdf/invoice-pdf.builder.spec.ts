import { InvoicePdfBuilder } from './invoice-pdf.builder';

const input = {
  title: 'Alignment Test',
  subtitle: 'Restaurant',
  invoiceNumber: 'INV-1',
  issuedAt: new Date('2026-11-23T00:00:00.000Z'),
  brandName: 'Brand',
  headerLines: ['Legal address'],
  meta: [{ label: 'Shop ID', value: '129' }],
  sections: [
    {
      title: 'Details',
      tables: [
        {
          columns: [{ header: 'Name', width: 200 }],
          rows: [['Alpha']],
        },
      ],
    },
  ],
};

describe('InvoicePdfBuilder direction', () => {
  it('left-aligns unspecified content for LTR PDFs', () => {
    const pdf = InvoicePdfBuilder.build({ ...input, direction: 'ltr' });
    const text = pdf.toString('utf8');

    expect(text).toContain('BT /F1 8 Tf 52');
    expect(text).toContain('Td (Alpha) Tj ET');
    expect(text).toContain('BT /F1 8.5 Tf 48');
    expect(text).toContain('Td (Legal address) Tj ET');
  });

  it('right-aligns body, metadata, tables, headers, and footer for RTL PDFs', () => {
    const pdf = InvoicePdfBuilder.build({ ...input, direction: 'rtl' });
    const text = pdf.toString('utf8');

    expect(text).not.toContain('BT /F1 8 Tf 52');
    expect(text).toContain('Td (Alpha) Tj ET');
    expect(text).not.toContain('BT /F1 8.5 Tf 48');
    expect(text).toContain('Td (Legal address) Tj ET');
    expect(text).toContain('(Shop ID: 129) Tj ET');
    expect(text).toContain('(Generated by DeliveryWay');
  });
});
